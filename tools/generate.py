#!/usr/bin/env python3
"""Build every derived config from theme/palette.json and settings.json.

Outputs go to ~/rice/generated/. Never edit those by hand: change the JSON
(or a template) and re-run this, or just run install.sh which calls it.
"""
import json
from pathlib import Path

RICE = Path(__file__).resolve().parent.parent
OUT = RICE / "generated"
HEADER = "Generated by tools/generate.py from theme/palette.json + settings.json. Do not edit."


def load():
    pal = json.loads((RICE / "theme/palette.json").read_text())
    settings = json.loads((RICE / "settings.json").read_text())
    ansi = {k: v for k, v in pal["ansi"].items() if not k.startswith("_")}
    return pal["name"], pal["colors"], ansi, settings


def hexbare(c):
    return c.lstrip("#").upper()


def lua_value(v, indent=0):
    pad = "    " * (indent + 1)
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return repr(v)
    if isinstance(v, str):
        return json.dumps(v)
    if isinstance(v, list):
        items = ",\n".join(pad + lua_value(x, indent + 1) for x in v)
        return "{\n" + items + "\n" + "    " * indent + "}"
    items = ",\n".join(f"{pad}[{json.dumps(k)}] = {lua_value(x, indent + 1)}" for k, x in v.items())
    return "{\n" + items + "\n" + "    " * indent + "}"


def terminal_colors(c, ansi):
    """The 16 ANSI colours, built from the palette."""
    return [
        c["surface"], c["red"], ansi["green"], c["warning"],
        ansi["blue"], c["magenta"], ansi["cyan"], c["text"],
        ansi["bright_black"], c["red"], ansi["bright_green"], ansi["bright_yellow"],
        ansi["bright_blue"], c["magenta"], ansi["bright_cyan"], "#FFFFFF",
    ]


def gen_lua(name, c, ansi, settings):
    # Hyprland wants bare hex inside rgb()/rgba(), so store bare hex here.
    colors = {k: hexbare(v) for k, v in {**c, **ansi}.items()}
    (OUT / "palette.lua").write_text(f"-- {HEADER}\nreturn {lua_value(colors)}\n")
    (OUT / "settings.lua").write_text(f"-- {HEADER}\nreturn {lua_value(settings)}\n")


def gen_kitty(name, c, ansi):
    lines = [
        f"# {HEADER}",
        f"foreground {c['text']}",
        f"background {c['base']}",
        f"selection_foreground {c['base']}",
        f"selection_background {c['red']}",
        f"cursor {c['red']}",
        f"cursor_text_color {c['base']}",
        f"url_color {c['magenta']}",
        f"active_border_color {c['red']}",
        f"inactive_border_color {c['overlay']}",
        f"bell_border_color {c['warning']}",
        f"active_tab_foreground {c['base']}",
        f"active_tab_background {c['red']}",
        f"inactive_tab_foreground {c['muted']}",
        f"inactive_tab_background {c['surface']}",
        f"tab_bar_background {c['base']}",
        f"mark1_background {c['red']}",
        f"mark2_background {c['magenta']}",
    ]
    lines += [f"color{i} {col}" for i, col in enumerate(terminal_colors(c, ansi))]
    (OUT / "kitty-colors.conf").write_text("\n".join(lines) + "\n")


def gen_css(c, ansi):
    body = "\n".join(f"  --{k.replace('_', '-')}: {v};" for k, v in {**c, **ansi}.items())
    (OUT / "palette.css").write_text(f"/* {HEADER} */\n:root {{\n{body}\n}}\n")


def gen_qml(c, ansi):
    props = "\n".join(f'    readonly property color {k}: "{v}"' for k, v in {**c, **ansi}.items())
    (OUT / "Theme.qml").write_text(
        f"// {HEADER}\npragma Singleton\nimport QtQuick\n\nQtObject {{\n{props}\n}}\n"
    )


def gen_qml_extras(settings):
    """Singleton registration + settings copy so Quickshell reads everything from one folder."""
    (OUT / "qmldir").write_text("singleton Theme 1.0 Theme.qml\n")
    (OUT / "settings.json").write_text(json.dumps(settings, indent=2) + "\n")


def gen_fish(c, ansi):
    h = {k: hexbare(v) for k, v in {**c, **ansi}.items()}
    vars_ = {
        "fish_color_normal": h["text"],
        "fish_color_command": f"{h['red']} --bold",
        "fish_color_keyword": h["magenta"],
        "fish_color_quote": h["green"],
        "fish_color_redirection": h["magenta"],
        "fish_color_end": h["magenta"],
        "fish_color_error": f"{h['warning']} --underline",
        "fish_color_param": h["text"],
        "fish_color_option": h["cyan"],
        "fish_color_comment": h["muted"],
        "fish_color_operator": h["magenta"],
        "fish_color_escape": h["cyan"],
        "fish_color_autosuggestion": h["muted"],
        "fish_color_valid_path": "--underline",
        "fish_color_search_match": f"--background={h['overlay']}",
        "fish_color_selection": f"{h['base']} --background={h['red']}",
        "fish_color_cancel": h["red_dim"],
        "fish_pager_color_prefix": f"{h['red']} --bold",
        "fish_pager_color_completion": h["text"],
        "fish_pager_color_description": h["muted"],
        "fish_pager_color_progress": f"{h['base']} --background={h['red']}",
        "fish_pager_color_selected_background": f"--background={h['overlay']}",
    }
    lines = [f"# {HEADER}"] + [f"set -g {k} {v}" for k, v in vars_.items()]
    (OUT / "colors.fish").write_text("\n".join(lines) + "\n")


def gen_starship(name, c, ansi):
    template = (RICE / "starship/starship.toml").read_text()
    table = "\n".join(f'{k} = "{v}"' for k, v in {**c, **ansi}.items())
    (OUT / "starship.toml").write_text(
        f"# {HEADER}\n# Template: starship/starship.toml\n\n"
        f'palette = "{name}"\n\n{template.rstrip()}\n\n[palettes.{name}]\n{table}\n'
    )


def main():
    OUT.mkdir(exist_ok=True)
    name, c, ansi, settings = load()
    gen_lua(name, c, ansi, settings)
    gen_kitty(name, c, ansi)
    gen_css(c, ansi)
    gen_qml(c, ansi)
    gen_qml_extras(settings)
    gen_fish(c, ansi)
    gen_starship(name, c, ansi)
    print(f"generated -> {OUT}")


if __name__ == "__main__":
    main()
